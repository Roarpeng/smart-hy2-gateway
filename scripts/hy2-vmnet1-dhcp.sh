#!/bin/bash
# ============================================================================
# hy2-vmnet1-dhcp.sh — VMnet1 Host-Only DHCP 配置（带默认网关/DNS）
#
# 背景:
#   VMware 自带的 Host-Only DHCP 默认只下发 IP，不下发 option routers，
#   Windows/Linux 虚拟机会出现“有 192.168.100.x 但没有默认网关”的状态。
#   本脚本在 vmware.service 启动后重写 vmnet1 的 dhcpd.conf，并由
#   hy2-vmnet1-dhcp.service 启动一个带网关/DNS 的 DHCP 服务。
#
# 固定拓扑:
#   VMnet1 = 192.168.100.0/24
#   宿主网关 = 192.168.100.1
#   地址池 = 192.168.100.128 - 192.168.100.254
# ============================================================================
set -euo pipefail

CONF=/etc/vmware/vmnet1/dhcpd/dhcpd.conf
LEASES=/etc/vmware/vmnet1/dhcpd/dhcpd.leases

# 等待 VMware 创建 vmnet1 宿主接口（最多 30 秒）
for _ in $(seq 1 30); do
    if ip link show vmnet1 >/dev/null 2>&1; then
        break
    fi
    sleep 1
done

if ! ip link show vmnet1 >/dev/null 2>&1; then
    echo "vmnet1 接口不存在，无法启动 DHCP" >&2
    exit 1
fi

install -d -m 755 /etc/vmware/vmnet1/dhcpd

cat > "$CONF" <<'EOF'
# Generated by hy2-vmnet1-dhcp.sh — do not edit by hand.
allow unknown-clients;
default-lease-time 1800;
max-lease-time 7200;

subnet 192.168.100.0 netmask 255.255.255.0 {
    range 192.168.100.128 192.168.100.254;
    option broadcast-address 192.168.100.255;
    option routers 192.168.100.1;
    option domain-name-servers 223.5.5.5, 1.1.1.1;
    option domain-name localdomain;
}

host vmnet1 {
    hardware ethernet 00:50:56:C0:00:01;
    fixed-address 192.168.100.1;
}
EOF

touch "$LEASES"
chmod 644 "$CONF" "$LEASES"
